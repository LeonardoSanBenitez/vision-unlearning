"""Repair the ``prompted_entity`` field of embedding files already written to disk.

Every scenes embedding file holds a doubled entity name -- ``an an abbey scene scene`` -- because two
name transforms were composed, each adding its own article and suffix. The transform is idempotent
from now on (see :mod:`vision_unlearning.datasets.entity_names`), so nothing new is written wrong;
this module fixes what is already on disk.

The payload is large, is not under version control, and comes from images that cost GPU-days to
reproduce, so nothing here rewrites a file in place. Per file:

1. read it, and derive the new value of every record from that record's own ``prompt``;
2. take a **semantic digest** over everything the repair must not touch -- the metadata, and each
   record's seed, prompt and embedding, in order -- plus the record count;
3. write a sibling ``<name>.tmp``;
4. reopen the temporary file and re-check the digest, the record count and the derivation;
5. ``os.replace`` it over the original, which is atomic on both Windows and POSIX;
6. append one line to the manifest, holding the old values, so the whole run is invertible.

A run that stops halfway can be resumed: files already in the manifest are skipped. If any step
before (5) fails, the original has not been touched and the temporary file is removed.

Run ``python -m vision_unlearning.benchmarks.I_care.repair_prompted_entity --help`` for the full
operating manual.

This is a one-off. Once the corpus is regenerated by the pipelines it should never need to run
again -- but it stays committed, with its tests, so the repair can be audited or inverted later.
"""
from __future__ import annotations

import argparse
import glob as globlib
import hashlib
import json
import os
import sys
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Any, Dict, List, Literal, Optional, Sequence, cast

from vision_unlearning.datasets.entity_names import canonical_entity, type_entity_task
from vision_unlearning.utils.logger import get_logger


logger = get_logger('unlearning_analysis')

#: Every generated prompt in the benchmark is this prefix followed by the canonical entity.
PROMPT_PREFIX = 'An image of '

#: One of: the file was rewritten; it was already correct; it would be rewritten (dry run);
#: it cannot be repaired and was left untouched.
type_repair_status = Literal['repaired', 'unchanged', 'would-change', 'refused']


@dataclass(frozen=True)
class FileRepairResult:
    """What happened to one file."""

    path: str
    status: type_repair_status
    n_records: int
    n_changed: int
    reason: Optional[str] = None


@dataclass(frozen=True)
class RepairSummary:
    """What happened to a whole run. ``n_seen`` is the sum of the other four."""

    n_seen: int
    n_repaired: int
    n_unchanged: int
    n_refused: int
    n_skipped_already_done: int
    results: List[FileRepairResult]


def prompted_entity_from_prompt(task: type_entity_task, prompt: str) -> str:
    """Return the entity name a record should carry, derived from that record's own ``prompt``.

    The prompt is the string the images were generated with, so it -- and not a lookup keyed on
    anything else -- is the authority on which entity a record describes.

    @param task: the task the file belongs to, taken from the file's own metadata block.
    @param prompt: the record's ``prompt`` field.
    @raises ValueError: the prompt is not a generation prompt, or its body is not already the
        canonical form of the entity. Either means the file cannot be repaired from itself, which
        is a finding rather than something to work around.
    """
    if not prompt.startswith(PROMPT_PREFIX):
        raise ValueError(f'not a generation prompt (expected the prefix {PROMPT_PREFIX!r}): {prompt!r}')
    body = prompt[len(PROMPT_PREFIX):]
    canonical = canonical_entity(task, body)
    if canonical != body:
        raise ValueError(
            f'the prompt body {body!r} is not the canonical form of the entity '
            f'(that would be {canonical!r}), so this file is not repairable from its own prompts'
        )
    return body


def semantic_digest(payload: Dict[str, Any]) -> str:
    """Return a digest over everything in *payload* that the repair must leave untouched.

    Covers the metadata block and, in order, every record's fields except ``prompted_entity``,
    plus the record count. A changed vector, a dropped record and a reordered record each change
    it; rewriting the field under repair does not.
    """
    records = payload.get('embeddings', [])
    shadow = {
        'metadata': payload.get('metadata'),
        'n_records': len(records),
        'records': [
            {key: value for key, value in record.items() if key != 'prompted_entity'}
            for record in records
        ],
        'other_keys': {
            key: value for key, value in payload.items()
            if key not in ('metadata', 'embeddings')
        },
    }
    encoded = json.dumps(shadow, sort_keys=True, separators=(',', ':'), ensure_ascii=False)
    return hashlib.sha256(encoded.encode('utf-8')).hexdigest()


def _task_of(payload: Dict[str, Any], path: str) -> type_entity_task:
    try:
        task = payload['metadata']['task']
    except (KeyError, TypeError):
        raise ValueError(f'no metadata.task in {path}: the task rule cannot be chosen')
    if task not in ('breeds', 'scenes', 'people'):
        raise ValueError(f'unsupported metadata.task {task!r} in {path}')
    return cast(type_entity_task, task)


def _expected_values(payload: Dict[str, Any], path: str) -> List[str]:
    """Return the correct ``prompted_entity`` of every record, in record order."""
    task = _task_of(payload, path)
    values: List[str] = []
    for index, record in enumerate(payload.get('embeddings', [])):
        if 'prompt' not in record:
            raise ValueError(f'record {index} of {path} has no prompt to derive the entity from')
        values.append(prompted_entity_from_prompt(task, record['prompt']))
    return values


def _validate_rewritten_file(
    tmp_path: str,
    expected_digest: str,
    expected_values: List[str],
) -> None:
    """Reopen the temporary file and check it is the original with only the field repaired.

    @raises RuntimeError: the reopened file disagrees on the digest, the record count, or any
        repaired value. The caller must then leave the original alone.
    """
    with open(tmp_path, encoding='utf-8') as handle:
        rewritten = json.load(handle)

    actual_digest = semantic_digest(rewritten)
    if actual_digest != expected_digest:
        raise RuntimeError(
            f'{tmp_path}: the rewritten file does not carry the original data '
            f'(digest {actual_digest} != {expected_digest})'
        )

    records = rewritten.get('embeddings', [])
    if len(records) != len(expected_values):
        raise RuntimeError(
            f'{tmp_path}: the rewritten file has {len(records)} records, expected {len(expected_values)}'
        )

    for index, (record, expected) in enumerate(zip(records, expected_values)):
        if record.get('prompted_entity') != expected:
            raise RuntimeError(
                f'{tmp_path}: record {index} holds {record.get("prompted_entity")!r}, expected {expected!r}'
            )


def _append_manifest(manifest_path: str, entry: Dict[str, Any]) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(manifest_path)), exist_ok=True)
    with open(manifest_path, 'a', encoding='utf-8') as handle:
        handle.write(json.dumps(entry, ensure_ascii=False) + '\n')


def read_manifest(manifest_path: str) -> List[Dict[str, Any]]:
    """Return every entry of the manifest, in the order it was written."""
    if not os.path.exists(manifest_path):
        return []
    entries: List[Dict[str, Any]] = []
    with open(manifest_path, encoding='utf-8') as handle:
        for line in handle:
            line = line.strip()
            if line:
                entries.append(json.loads(line))
    return entries


def repair_file(path: str, manifest_path: str, dry_run: bool = False) -> FileRepairResult:
    """Repair one embedding file, or report why it cannot be repaired.

    @param path: the embedding JSON file.
    @param manifest_path: where one line per processed file is appended. Written only after the
        replace has succeeded, and not at all on a dry run.
    @param dry_run: report what would change and write nothing.
    @raises RuntimeError: the rewritten file failed validation. The original is untouched.
    """
    with open(path, encoding='utf-8') as handle:
        payload = json.load(handle)

    records = payload.get('embeddings', [])
    try:
        expected_values = _expected_values(payload, path)
    except ValueError as error:
        logger.warning('Refusing %s: %s', path, error)
        return FileRepairResult(path=path, status='refused', n_records=len(records), n_changed=0, reason=str(error))

    old_values = [record.get('prompted_entity') for record in records]
    n_changed = sum(1 for old, new in zip(old_values, expected_values) if old != new)

    if n_changed == 0:
        return FileRepairResult(path=path, status='unchanged', n_records=len(records), n_changed=0)

    if dry_run:
        return FileRepairResult(path=path, status='would-change', n_records=len(records), n_changed=n_changed)

    expected_digest = semantic_digest(payload)
    for record, new_value in zip(records, expected_values):
        record['prompted_entity'] = new_value

    tmp_path = f'{path}.tmp'
    try:
        with open(tmp_path, 'w', encoding='utf-8') as handle:
            json.dump(payload, handle)
        _validate_rewritten_file(tmp_path, expected_digest, expected_values)
        os.replace(tmp_path, path)
    except BaseException:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)
        raise

    _append_manifest(manifest_path, {
        'file': os.path.abspath(path),
        'at': datetime.now(timezone.utc).isoformat(),
        'digest': expected_digest,
        'n_records': len(records),
        'n_changed': n_changed,
        'old_prompted_entity': old_values,
    })
    return FileRepairResult(path=path, status='repaired', n_records=len(records), n_changed=n_changed)


def repair_all(paths: Sequence[str], manifest_path: str, dry_run: bool = False) -> RepairSummary:
    """Repair every file in *paths*, skipping any the manifest already records as done."""
    already_done = {entry['file'] for entry in read_manifest(manifest_path)}
    results: List[FileRepairResult] = []
    n_skipped = 0

    for path in paths:
        if os.path.abspath(path) in already_done:
            n_skipped += 1
            logger.info('Already in the manifest, skipping: %s', path)
            continue
        results.append(repair_file(path, manifest_path=manifest_path, dry_run=dry_run))

    return RepairSummary(
        n_seen=len(paths),
        n_repaired=sum(1 for r in results if r.status in ('repaired', 'would-change')),
        n_unchanged=sum(1 for r in results if r.status == 'unchanged'),
        n_refused=sum(1 for r in results if r.status == 'refused'),
        n_skipped_already_done=n_skipped,
        results=results,
    )


def invert(manifest_path: str) -> int:
    """Put every value the manifest recorded back, newest entry first. Returns the file count."""
    n_restored = 0
    for entry in reversed(read_manifest(manifest_path)):
        path = entry['file']
        if not os.path.exists(path):
            logger.warning('Cannot invert, file is gone: %s', path)
            continue
        with open(path, encoding='utf-8') as handle:
            payload = json.load(handle)
        records = payload.get('embeddings', [])
        old_values = entry['old_prompted_entity']
        if len(records) != len(old_values):
            logger.warning('Cannot invert %s: %d records, manifest holds %d', path, len(records), len(old_values))
            continue
        for record, old_value in zip(records, old_values):
            record['prompted_entity'] = old_value
        with open(path, 'w', encoding='utf-8') as handle:
            json.dump(payload, handle)
        n_restored += 1
    return n_restored


def audit(paths: Sequence[str]) -> Dict[str, Any]:
    """Read every file and report, without writing anything, how many records are already correct.

    This is the read-only counterpart of the repair: it recomputes the expected value from each
    record's own prompt and compares, so it can be run over files this utility never touched.
    """
    n_files_correct = 0
    n_files_wrong = 0
    n_files_unreadable = 0
    n_records = 0
    n_records_wrong = 0
    wrong_examples: List[Dict[str, Any]] = []

    for path in paths:
        try:
            with open(path, encoding='utf-8') as handle:
                payload = json.load(handle)
            expected_values = _expected_values(payload, path)
        except (ValueError, OSError, json.JSONDecodeError) as error:
            n_files_unreadable += 1
            wrong_examples.append({'file': path, 'error': str(error)})
            continue

        records = payload.get('embeddings', [])
        n_records += len(records)
        wrong_here = [
            (index, record.get('prompted_entity'), expected)
            for index, (record, expected) in enumerate(zip(records, expected_values))
            if record.get('prompted_entity') != expected
        ]
        n_records_wrong += len(wrong_here)
        if wrong_here:
            n_files_wrong += 1
            if len(wrong_examples) < 5:
                index, found, expected = wrong_here[0]
                wrong_examples.append({'file': path, 'record': index, 'found': found, 'expected': expected})
        else:
            n_files_correct += 1

    return {
        'n_files': len(paths),
        'n_files_correct': n_files_correct,
        'n_files_wrong': n_files_wrong,
        'n_files_unreadable': n_files_unreadable,
        'n_records': n_records,
        'n_records_wrong': n_records_wrong,
        'examples': wrong_examples,
    }


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog='python -m vision_unlearning.benchmarks.I_care.repair_prompted_entity',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        description=(
            'Repair the prompted_entity field of embedding files already on disk.\n\n'
            'Every scenes embedding file holds a doubled name ("an an abbey scene scene") because two\n'
            'name transforms were composed. The correct value is derived from each record\'s own prompt,\n'
            'which is the string its images were generated with. Nothing else in the file is touched,\n'
            'and a digest over everything else is checked before and after the rewrite.'
        ),
        epilog=(
            'PROCEDURE\n'
            '  1. --audit first. It writes nothing and tells you how many files and records are wrong.\n'
            '  2. --dry-run next, with the --manifest you intend to use. Same reading, plus the exact\n'
            '     set of files that would be rewritten.\n'
            '  3. the real run. Every rewritten file appends one line to the manifest.\n'
            '  4. --audit again: it must report 0 wrong records.\n'
            '  5. a second real run: it must report 0 repaired, every file unchanged.\n\n'
            'IF SOMETHING GOES WRONG\n'
            '  --invert puts every value the manifest recorded back, newest first. The manifest is the\n'
            '  only thing needed for that, so keep it: it is a few megabytes and the corpus is a gigabyte.\n\n'
            'WHAT THE STATUSES MEAN\n'
            '  repaired      the file was rewritten and the manifest has its old values.\n'
            '  unchanged     every record already held the right value; nothing was written.\n'
            '  would-change  --dry-run only: this file would be rewritten.\n'
            '  refused       the file cannot be repaired from itself -- a prompt is not a generation\n'
            '                prompt, or its body is not the canonical entity form, or metadata.task is\n'
            '                missing. Nothing was written. This is a finding: report it, do not work\n'
            '                around it.\n\n'
            'SAFETY\n'
            '  The original is replaced only after a sibling .tmp file has been written, reopened and\n'
            '  validated. Any failure before that leaves the original byte-identical and removes the\n'
            '  temporary file. A run that dies halfway is resumed by repeating the same command: files\n'
            '  already in the manifest are skipped.\n\n'
            'EXIT CODES\n'
            '  0  every file was repaired, unchanged, or skipped as already done.\n'
            '  1  at least one file was refused, or --audit found wrong records.\n\n'
            'EXAMPLES\n'
            '  ... --datasets-dir vision_unlearning/benchmarks/I_care/assets/datasets --audit\n'
            '  ... --datasets-dir <dir> --pattern "embeddings_scenes_*.json" --manifest repair.jsonl --dry-run\n'
            '  ... --datasets-dir <dir> --pattern "embeddings_scenes_*.json" --manifest repair.jsonl\n'
            '  ... --manifest repair.jsonl --invert\n'
        ),
    )
    parser.add_argument(
        '--datasets-dir',
        help='directory holding the embedding JSON files. Required unless --invert is given.',
    )
    parser.add_argument(
        '--pattern', default='embeddings_*.json',
        help='glob applied inside --datasets-dir (default: %(default)s). Use embeddings_scenes_*.json '
             'to touch only the task that is known to be wrong.',
    )
    parser.add_argument(
        '--manifest',
        help='JSON-lines file, appended to, one line per rewritten file, holding its old values. '
             'Required for a real or dry run; it is also the input of --invert.',
    )
    parser.add_argument('--dry-run', action='store_true', help='report what would change and write nothing.')
    parser.add_argument('--audit', action='store_true', help='read-only: count how many records hold the wrong value.')
    parser.add_argument('--invert', action='store_true', help='restore every value recorded in --manifest.')
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)

    if args.invert:
        if not args.manifest:
            parser.error('--invert needs --manifest')
        n_restored = invert(args.manifest)
        print(f'INVERTED {n_restored} file(s) from {args.manifest}')
        return 0

    if not args.datasets_dir:
        parser.error('--datasets-dir is required')
    paths = sorted(globlib.glob(os.path.join(args.datasets_dir, args.pattern)))
    print(f'{len(paths)} file(s) match {args.pattern!r} in {args.datasets_dir}')

    if args.audit:
        report = audit(paths)
        print(json.dumps({key: value for key, value in report.items() if key != 'examples'}, indent=2))
        for example in report['examples']:
            print(f'  example: {example}')
        return 1 if (report['n_records_wrong'] or report['n_files_unreadable']) else 0

    if not args.manifest:
        parser.error('--manifest is required for a dry run and for a real run')

    summary = repair_all(paths, manifest_path=args.manifest, dry_run=args.dry_run)
    label = 'would repair' if args.dry_run else 'repaired'
    print(
        f'{label}={summary.n_repaired} unchanged={summary.n_unchanged} '
        f'refused={summary.n_refused} skipped_already_done={summary.n_skipped_already_done} '
        f'seen={summary.n_seen}'
    )
    for result in summary.results:
        if result.status == 'refused':
            print(f'  REFUSED {result.path}: {result.reason}')
    return 1 if summary.n_refused else 0


if __name__ == '__main__':
    sys.exit(main())
