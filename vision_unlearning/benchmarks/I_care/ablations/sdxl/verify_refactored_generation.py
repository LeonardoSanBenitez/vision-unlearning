'''Does the refactored library function reproduce the validated images, and do new seeds hold?

Everything validated so far was generated by ablation scripts driving the pipeline directly.
`generate_dataset` now takes the arguments those scripts needed -- guidance, the three Stable
Diffusion XL size arguments, and a `GenerationRuntime` carrying the memory and kernel settings -- so
the production path can produce the same images. This run checks that claim instead of asserting it,
and answers two more questions at the same time.

    --stage base     one call, `generate_dataset` with the frozen hyperparameters, prompts=[target],
                     seeds=[42, 101, 202, 303, 404]. Five images:
                       * seed 42 is the CROSS-PROCESS test. The sign-off run generated the same
                         entity, seed and settings in a different process through the pipeline
                         directly; the mean absolute pixel difference between the two answers both
                         "does the library path equal the validated path" and "does a fresh process
                         reproduce an earlier one", which matters because deterministic algorithms
                         are off at 768.
                       * seeds 101, 202, 303 and 404 have never been used here. At 512 two seeds in
                         five produced ten unusable images each, so the question "does 768 hold for
                         seeds we did not pick" is not rhetorical.
    --stage adapter  one call with `lora_name` set to the seed-42 epoch-200 adapter, same entity and
                     seed. One image, compared against the sign-off run's adapted image, which
                     exercises the same cross-process question on the path that builds its pipeline
                     inside `unlearn_lora`.

The two stages are separate processes on purpose: each `generate_dataset` call builds its own
pipeline, and two Stable Diffusion XL pipelines in one process is the condition measured to drive
free system memory to about 1.3 GB.

    PYTHONPATH=<repo root> HF_HUB_DISABLE_XET=1 python verify_refactored_generation.py --stage base
'''
from __future__ import annotations

import argparse
import json
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

from run_campaign import _MODEL_ID, _VARIANT, _generation_order
from watchdog import ResourceMonitor, check_headroom

_HERE = Path(__file__).resolve().parent
_OUT = _HERE / "assets"
_IMAGES = _OUT / "verify_refactored"
_SIGN_OFF = _OUT / "validate_generation_768"
_ADAPTER = _OUT / "campaign_model" / "seed42" / "epoch-200"
_RESULT_TEMPLATE = "verify_refactored_{stage}.json"

_ENTITY = "Mark_Philippoussis"
_RESOLUTION = 768
_BASE_SEEDS = [42, 101, 202, 303, 404]
_ADAPTER_SEEDS = [42]

# The frozen generation hyperparameters, and the runtime settings 768 needs on this card.
_GENERATION_KWARGS: Dict[str, Any] = {
    "height": _RESOLUTION,
    "width": _RESOLUTION,
    "guidance_scale": 7.5,
    "original_size": (1024, 1024),
    "target_size": (1024, 1024),
    "crops_coords_top_left": (0, 0),
}


def _mean_abs_difference(left: Path, right: Path) -> Optional[float]:
    import numpy as np
    from PIL import Image
    if not (left.is_file() and right.is_file()):
        return None
    with Image.open(left) as a, Image.open(right) as b:
        first = np.asarray(a.convert("RGB"), dtype=np.int64)
        second = np.asarray(b.convert("RGB"), dtype=np.int64)
    if first.shape != second.shape:
        return None
    return round(float(np.mean(np.abs(first - second))), 4)


def main() -> None:
    from vision_unlearning.utils.data_generation import GenerationRuntime, generate_dataset

    parser = argparse.ArgumentParser(description="Verify the refactored generate_dataset on the card.")
    parser.add_argument("--stage", choices=["base", "adapter"], required=True)
    arguments = parser.parse_args()

    check_headroom()
    _IMAGES.mkdir(parents=True, exist_ok=True)

    prompt = {entry["name"]: entry["prompt"] for entry in _generation_order()}[_ENTITY]
    seeds = _BASE_SEEDS if arguments.stage == "base" else _ADAPTER_SEEDS
    lora_name = None if arguments.stage == "base" else str(_ADAPTER)
    if lora_name is not None:
        assert (_ADAPTER / "pytorch_lora_weights.safetensors").is_file(), f"adapter missing: {_ADAPTER}"

    filenames = [f"{arguments.stage}_{_ENTITY}_seed{seed}.png" for seed in seeds]
    runtime = GenerationRuntime(
        attention_slice_size=1,
        vae_slicing=True,
        vae_tiling=True,
        vae_tile_sample_min_size=512,
        deterministic_algorithms=False,
        device_map="balanced",
    )

    monitor = ResourceMonitor(_OUT / f"verify_refactored_{arguments.stage}_monitor.log", interval_s=15.0)
    monitor.start()
    t0 = time.time()
    try:
        metadata = generate_dataset(
            model_base_name=_MODEL_ID,
            lora_name=lora_name,
            prompts=[prompt],
            output_path=str(_IMAGES),
            filenames=filenames,
            seeds=seeds,
            batch_size=1,
            lora_requires_inversion=False,
            variant=_VARIANT,
            runtime=runtime,
            **_GENERATION_KWARGS,
        )
    finally:
        monitor.stop()
    seconds = round(time.time() - t0, 1)

    # The cross-process comparison: the sign-off run made the same image in another process, through
    # the pipeline directly rather than through this function.
    reference = (_SIGN_OFF / f"off_{_ENTITY}_seed42.png" if arguments.stage == "base"
                 else _SIGN_OFF / f"on_epoch200_{_ENTITY}_seed42.png")
    produced = _IMAGES / f"{arguments.stage}_{_ENTITY}_seed42.png"
    difference = _mean_abs_difference(produced, reference)

    results: Dict[str, Any] = {
        "stage": arguments.stage,
        "entity": _ENTITY,
        "prompt": prompt,
        "seeds": seeds,
        "resolution": _RESOLUTION,
        "generation_hyperparameters": {k: list(v) if isinstance(v, tuple) else v
                                       for k, v in _GENERATION_KWARGS.items()},
        "runtime": runtime.__dict__,
        "images": [str(_IMAGES / name) for name in filenames],
        "metadata_rows": len(metadata),
        "seconds": seconds,
        "cross_process_comparison": {
            "produced": str(produced),
            "reference": str(reference),
            "mean_abs_difference": difference,
        },
        "peak_vram_used_gb": round(monitor.peak_vram_used_gb, 3),
        "min_ram_free_gb": (round(monitor.min_ram_free_gb, 3)
                            if monitor.min_ram_free_gb != float("inf") else None),
    }
    (_OUT / _RESULT_TEMPLATE.format(stage=arguments.stage)).write_text(
        json.dumps(results, indent=2), encoding="utf-8")

    written: List[str] = [name for name in filenames if (_IMAGES / name).is_file()]
    print(f"cross-process mean absolute pixel difference against the sign-off image: {difference}")
    print(f"VERIFY_REFACTORED_DONE stage={arguments.stage} images_written={len(written)} of "
          f"{len(filenames)} seconds={seconds} "
          f"peak_vram_used_gb={results['peak_vram_used_gb']} "
          f"min_ram_free_gb={results['min_ram_free_gb']}")


if __name__ == "__main__":
    main()
