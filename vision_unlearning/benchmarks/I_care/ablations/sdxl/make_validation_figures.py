'''Figures for the mid-task validation report (plan stage S7.5).

Four figures, each answering one question a reader of the validation report has to be able to check for
themselves, with the number printed beside the image it was computed from:

1. `validation_noise_floor_demonstration.png` -- what a noise floor IS. Three entities, each rendered
   twice from the SAME unmodified base model, differing only in the random seed. Nothing was unlearned
   between the two columns, so any difference in the CLIP score is produced by the random draw alone.
2. `validation_target_progression.png` -- the target across every checkpoint, both seeds, with its
   `clip_diff` under each image. This is the figure that lets a human judge whether the metric agrees
   with what the pictures show.
3. `validation_receiver_progression.png` -- the same for three receivers chosen by their measured
   behaviour, not by hand: the most negative, the most positive, and the quietest.
4. `validation_clip_diff_curves.png` -- every entity's `clip_diff` over the epoch axis with the measured
   noise-floor band drawn on it, which is the figure an acceptability threshold would have to be read
   off.

It also runs the progression-consistency check `CONTRIBUTING_REPORTS.md` section 6 requires: the mean
absolute pixel difference between adjacent columns, computed over the entities that should change
smoothly, with any transition above twice the median flagged. The off-baseline-to-first-epoch transition
is checked separately because a baseline generated by a different code path or prompt ordering shows up
exactly there, and that is this project's most expensive recurring figure bug.

Reads only artifacts already on disk. Generates no image with any model.

    python make_validation_figures.py
'''
from __future__ import annotations

import json
import statistics
from pathlib import Path
from typing import Any, Dict, List, Tuple

import campaign_configuration as cfg

_HERE = Path(__file__).resolve().parent
_OUT = _HERE / "assets"
_REFERENCE_FLOOR = _HERE.parent / "every_epoch" / "assets" / "noise_floor_people.json"


def _display(name: str) -> str:
    return name.replace("_", " ")


def _load() -> Tuple[Dict[str, Any], Dict[str, Any]]:
    campaign = json.loads((_OUT / "clip_diff_campaign.json").read_text(encoding="utf-8"))
    floor = json.loads((_OUT / "noise_floor_people_sdxl.json").read_text(encoding="utf-8"))
    return campaign, floor


def _strip(axes: Any, image_path: str, title: str) -> None:
    from PIL import Image
    axes.imshow(Image.open(image_path).convert("RGB"))
    axes.set_title(title, fontsize=7)
    axes.set_xticks([])
    axes.set_yticks([])


def figure_noise_floor(campaign: Dict[str, Any], floor: Dict[str, Any]) -> Path:
    """Same prompt, same unmodified model, two random draws -- with both CLIP scores."""
    import matplotlib.pyplot as plt

    ranked = sorted(floor["per_entity"], key=lambda name: -floor["per_entity"][name])
    chosen = [ranked[0], ranked[len(ranked) // 2], ranked[-1]]
    seeds = [str(seed) for seed in floor["seeds"]]

    fig, axes = plt.subplots(len(chosen), len(seeds), figsize=(6.4, 3.2 * len(chosen)))
    for row, name in enumerate(chosen):
        entry = floor["base_scores"][name]
        for column, seed in enumerate(seeds):
            score = entry["per_seed_clip"][seed]
            _strip(axes[row][column], entry["paths"][seed],
                   f"seed {seed}, clip score {score:.2f}")
        axes[row][0].set_ylabel(f"{_display(name)}\nabsolute difference {floor['per_entity'][name]:.2f}",
                                fontsize=7)
    fig.suptitle("base model only, no unlearning applied; prompt fixed per row; seed varies across columns\n"
                 f"model={cfg.MODEL_ID} resolution={cfg.GENERATION_RESOLUTION} steps=50 "
                 f"noise_floor_median={floor['summary']['median']:.2f} "
                 f"noise_floor_maximum={floor['summary']['maximum']:.2f}", fontsize=8)
    fig.tight_layout(rect=(0, 0, 1, 0.94))
    path = _OUT / "validation_noise_floor_demonstration.png"
    fig.savefig(path, dpi=110)
    plt.close(fig)
    return path


def _progression_rows(campaign: Dict[str, Any], rows: List[Tuple[str, int]], path: Path, title: str) -> Path:
    """One row per (entity, seed): the off baseline then every checkpoint, clip_diff under each."""
    import matplotlib.pyplot as plt

    first_seed = str(rows[0][1])
    epochs: List[int] = campaign["per_seed"][first_seed]["epochs"]
    columns = 1 + len(epochs)
    # 2.55 inches per row rather than 2.0: at 2.0 the two-line per-cell titles of one row landed on top
    # of the images of the row above.
    fig, axes = plt.subplots(len(rows), columns, figsize=(1.55 * columns, 2.55 * len(rows)))
    axes = axes.reshape(len(rows), columns)
    for row, (name, seed) in enumerate(rows):
        entry = campaign["per_seed"][str(seed)]["per_entity"][name]
        off_path = entry["trajectory"][0]["path"]
        off_directory = Path(off_path).parent
        off_file = off_directory / f"off_{name}_seed{seed}.png"
        _strip(axes[row][0], str(off_file), f"off baseline\nclip score {entry['clip_off']:.2f}")
        for column, point in enumerate(entry["trajectory"], start=1):
            _strip(axes[row][column], point["path"],
                   f"epoch {point['epoch']}\nclip_diff {point['clip_diff']:+.2f}")
        axes[row][0].set_ylabel(f"{_display(name)}\nseed {seed}", fontsize=7)
    fig.suptitle(title, fontsize=8)
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig.savefig(path, dpi=100)
    plt.close(fig)
    return path


def figure_off_baseline_contact_sheet(campaign: Dict[str, Any], floor: Dict[str, Any]) -> Path:
    """Every off-baseline image in the campaign, so the reader judges the population and not a sample.

    The base model's rendering quality at 512 was accepted on ONE probe image (plan section 5). This
    sheet puts all `seeds x entities` of them on one page with their CLIP scores, which is the
    denominator any statement about "the images look like X" has to be made against.
    """
    import matplotlib.pyplot as plt

    seeds = [str(seed) for seed in campaign["seeds"]]
    entities = [campaign["target"]] + campaign["receivers"]
    fig, axes = plt.subplots(len(seeds), len(entities), figsize=(2.05 * len(entities), 2.75 * len(seeds)))
    axes = axes.reshape(len(seeds), len(entities))
    for row, seed in enumerate(seeds):
        for column, name in enumerate(entities):
            entry = campaign["per_seed"][seed]["per_entity"][name]
            off_file = Path(entry["trajectory"][0]["path"]).parent / f"off_{name}_seed{seed}.png"
            marker = " (target)" if name == campaign["target"] else ""
            _strip(axes[row][column], str(off_file),
                   f"{_display(name)}{marker}\nclip score {entry['clip_off']:.2f}")
        axes[row][0].set_ylabel(f"seed {seed}", fontsize=8)
    fig.suptitle("every off-baseline image in the campaign: base model, no adapter, prompt "
                 "'An image of <entity>'\n"
                 f"model={cfg.MODEL_ID} resolution={cfg.GENERATION_RESOLUTION} steps=50 "
                 f"n={len(seeds)} seeds x {len(entities)} entities = {len(seeds) * len(entities)} images", fontsize=9)
    fig.tight_layout(rect=(0, 0, 1, 0.93))
    path = _OUT / "validation_off_baseline_contact_sheet.png"
    fig.savefig(path, dpi=95)
    plt.close(fig)
    return path


def figure_curves(campaign: Dict[str, Any], floor: Dict[str, Any]) -> Path:
    """clip_diff over the epoch axis, one panel per seed, with the measured noise-floor band."""
    import matplotlib.pyplot as plt

    reference = json.loads(_REFERENCE_FLOOR.read_text(encoding="utf-8"))["summary"]
    seeds = [str(seed) for seed in campaign["seeds"]]
    target = campaign["target"]
    fig, axes = plt.subplots(1, len(seeds), figsize=(7.0 * len(seeds), 5.2), sharey=True)
    for index, seed in enumerate(seeds):
        panel = axes[index]
        block = campaign["per_seed"][seed]
        epochs = block["epochs"]
        panel.axhspan(-floor["summary"]["median"], floor["summary"]["median"],
                      color="tab:orange", alpha=0.18, zorder=0)
        panel.axhspan(-floor["summary"]["maximum"], floor["summary"]["maximum"],
                      color="tab:orange", alpha=0.08, zorder=0)
        panel.axhline(0.0, color="black", linewidth=0.6, zorder=1)
        for name, entry in block["per_entity"].items():
            values = [point["clip_diff"] for point in entry["trajectory"]]
            if name == target:
                panel.plot(epochs, values, color="black", linewidth=2.6, zorder=5,
                           label=f"{_display(name)} (target)")
            else:
                panel.plot(epochs, values, linewidth=1.1, alpha=0.85, label=_display(name))
        panel.set_xscale("log")
        panel.set_xlabel("epoch (logarithmic axis)")
        panel.set_title(f"seed {seed}: clip_diff per entity, n=10 entities x {len(epochs)} checkpoints")
    axes[0].set_ylabel("clip_diff = clip score with adapter - clip score without adapter")
    axes[-1].legend(fontsize=7, loc="lower left", ncol=2)
    fig.suptitle(f"model={cfg.MODEL_ID}, spare, task={cfg.TASK}, "
                 f"resolution={cfg.GENERATION_RESOLUTION}, {_hyperparameters_shown()}; "
                 "shaded bands are the measured noise floor\n"
                 f"stable_diffusion_xl_floor_median={floor['summary']['median']:.2f} "
                 f"maximum={floor['summary']['maximum']:.2f}; "
                 f"stable_diffusion_1_4_floor_median={reference['median']:.2f} "
                 f"maximum={reference['maximum']:.2f}", fontsize=9)
    fig.tight_layout(rect=(0, 0, 1, 0.90))
    path = _OUT / "validation_clip_diff_curves.png"
    fig.savefig(path, dpi=120)
    plt.close(fig)
    return path


def _hyperparameters_shown() -> str:
    """The hyperparameters the campaign was actually TRAINED under, read from the training record.

    Not from a constant in this file and not from the runner's module constants: the training record
    is what the run wrote down about itself, so a figure title cannot drift away from the adapters it
    describes. This title used to name a hyperparameter grouping that had since been dropped, and to
    name the wrong one of the two settings -- a hand-written title outlived two decisions.
    """
    record = json.loads((_OUT / "campaign_train_seed42.json").read_text(encoding="utf-8"))
    values = record["hyperparameters"]
    return (f"learning_rate={values['learning_rate']:g} lora_r={values['lora_r']} "
            f"lora_alpha={values['lora_alpha']} forget_weight={values['forget_weight']}")


def progression_consistency(campaign: Dict[str, Any], seed: int) -> Dict[str, Any]:
    """Mean absolute pixel difference between adjacent columns, over the entities that should be quiet.

    `CONTRIBUTING_REPORTS.md` section 6: a progression figure needs a quantitative check, and the
    off-baseline-to-first-epoch transition is checked separately because a baseline produced by a
    different code path or prompt ordering shows up precisely there. The control units are the entities
    whose measured clip_diff never leaves the noise floor -- the ones being deliberately changed
    legitimately jump, so including them would hide exactly what this looks for.
    """
    import numpy as np
    from PIL import Image

    block = campaign["per_seed"][str(seed)]
    floor = json.loads((_OUT / "noise_floor_people_sdxl.json").read_text(encoding="utf-8"))
    median_floor = floor["summary"]["median"]
    controls = [name for name, entry in block["per_entity"].items()
                if max(abs(point["clip_diff"]) for point in entry["trajectory"]) <= median_floor]

    def mean_absolute_difference(first: str, second: str) -> float:
        a = np.asarray(Image.open(first).convert("RGB"), dtype=np.float64)
        b = np.asarray(Image.open(second).convert("RGB"), dtype=np.float64)
        return float(np.abs(a - b).mean())

    baseline_transitions: List[float] = []
    interior_transitions: List[float] = []
    for name in controls:
        entry = block["per_entity"][name]
        paths = [point["path"] for point in entry["trajectory"]]
        off_file = Path(paths[0]).parent / f"off_{name}_seed{seed}.png"
        baseline_transitions.append(mean_absolute_difference(str(off_file), paths[0]))
        interior_transitions.extend(mean_absolute_difference(paths[i], paths[i + 1])
                                    for i in range(len(paths) - 1))

    interior_median = statistics.median(interior_transitions) if interior_transitions else float("nan")
    flagged = [value for value in baseline_transitions if value > 2.0 * interior_median]
    return {
        "seed": seed,
        "control_entities": controls,
        "number_of_control_entities": len(controls),
        "interior_transition_median": interior_median,
        "interior_transition_maximum": max(interior_transitions) if interior_transitions else float("nan"),
        "baseline_to_first_epoch_median": statistics.median(baseline_transitions) if baseline_transitions else float("nan"),
        "baseline_to_first_epoch_values": baseline_transitions,
        "number_of_baseline_transitions_above_twice_interior_median": len(flagged),
    }


def main() -> None:
    import matplotlib
    matplotlib.use("Agg")

    campaign, floor = _load()
    target = campaign["target"]
    seeds = campaign["seeds"]

    written: List[Path] = [figure_noise_floor(campaign, floor)]
    written.append(_progression_rows(
        campaign, [(target, seed) for seed in seeds],
        _OUT / "validation_target_progression.png",
        "target across every checkpoint, one row per seed; "
        f"model={cfg.MODEL_ID} method=spare task={cfg.TASK} "
        f"resolution={cfg.GENERATION_RESOLUTION}"))

    # The three receivers are chosen from the measurements, never by eye: the most negative, the most
    # positive, and the one that moves least across the whole trajectory.
    reference_seed = str(seeds[0])
    block = campaign["per_seed"][reference_seed]["per_entity"]
    receivers = {name: entry for name, entry in block.items() if name != target}
    extreme = {name: [point["clip_diff"] for point in entry["trajectory"]] for name, entry in receivers.items()}
    most_negative = min(extreme, key=lambda name: min(extreme[name]))
    most_positive = max(extreme, key=lambda name: max(extreme[name]))
    quietest = min(extreme, key=lambda name: max(abs(value) for value in extreme[name]))
    written.append(_progression_rows(
        campaign, [(most_negative, seeds[0]), (most_positive, seeds[0]), (quietest, seeds[0])],
        _OUT / "validation_receiver_progression.png",
        f"three receivers at seed {seeds[0]}, selected by measured clip_diff: most negative "
        f"({_display(most_negative)}), most positive ({_display(most_positive)}), "
        f"smallest absolute movement ({_display(quietest)})"))
    written.append(figure_off_baseline_contact_sheet(campaign, floor))
    written.append(figure_curves(campaign, floor))

    checks = {str(seed): progression_consistency(campaign, seed) for seed in seeds}
    (_OUT / "validation_progression_check.json").write_text(json.dumps(checks, indent=2), encoding="utf-8")

    for seed, check in checks.items():
        print(f"seed {seed}: control entities (never leaving the noise floor): "
              f"{check['number_of_control_entities']} of 9 receivers -> {check['control_entities']}")
        print(f"  interior transition mean absolute pixel difference: median "
              f"{check['interior_transition_median']:.3f}, maximum {check['interior_transition_maximum']:.3f}")
        print(f"  off-baseline to first epoch: median {check['baseline_to_first_epoch_median']:.3f}, "
              f"values {[round(v, 3) for v in check['baseline_to_first_epoch_values']]}")
        print(f"  baseline transitions above twice the interior median: "
              f"{check['number_of_baseline_transitions_above_twice_interior_median']} of "
              f"{len(check['baseline_to_first_epoch_values'])}")
    for path in written:
        print(f"written: {path}")


if __name__ == "__main__":
    main()
