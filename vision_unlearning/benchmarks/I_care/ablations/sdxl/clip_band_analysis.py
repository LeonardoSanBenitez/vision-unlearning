'''What CLIP score corresponds to what kind of image, and what size of clip_diff is real?

The report needs both, and neither is answerable from the metric's definition -- only from putting
scores beside images somebody has looked at. Every group below is labelled BY EYE, from the contact
sheets named in `_GROUPS`, and the labels were fixed before these statistics were computed.

Two outputs:

1. A band table: for each visual class, the CLIP distribution over its images. That says what a
   score of 22, or 30, or 35 actually means.
2. The noise floor for `clip_diff`: the spread of CLIP across GOOD images of the same entity at
   different seeds. `clip_diff = clip_on - clip_off` is a difference between two such images, so a
   difference smaller than this spread cannot be told from the seed.

    PYTHONPATH=<repo root> python clip_band_analysis.py
'''
from __future__ import annotations

import json
from pathlib import Path
from statistics import mean, median, pstdev
from typing import Any, Callable, Dict, List, Tuple

_HERE = Path(__file__).resolve().parent
_OUT = _HERE / "assets"
_METRICS = _OUT / "render_quality_metrics.json"
_RESULT = _OUT / "clip_band_analysis.json"
_TABLE = _OUT / "clip_band_tables.md"

# label -> (what the eye saw, which contact sheet it was judged on, selector)
_GROUPS: List[Tuple[str, str, str, Callable[[Dict[str, Any]], bool]]] = [
    ("no person at all", "collages of glyphs and colour blocks, nothing recognisable",
     "overnight_block1_baselines.png, seed 45 row",
     lambda r: r["block"] == "1_baselines_alone" and r["seed"] == 45),
    ("person, not photographic", "posterised line drawings of a person",
     "overnight_block1_baselines.png, seed 43 row",
     lambda r: r["block"] == "1_baselines_alone" and r["seed"] == 43),
    ("stylised illustration", "comic-book style, the right person, clearly not a photograph",
     "overnight_block1_baselines.png, seed 44 row",
     lambda r: r["block"] == "1_baselines_alone" and r["seed"] == 44),
    ("photograph, 512 pixels", "photographic and correct",
     "overnight_block1_baselines.png, seed 42 row",
     lambda r: r["block"] == "1_baselines_alone" and r["seed"] == 42),
    ("photograph, 768 pixels", "photographic and correct",
     "figure_sign_off_768.png, all twenty cells",
     lambda r: r["block"] == "sign_off_768_off"),
]

_NOISE_FLOOR_ENTITY = "Mark_Philippoussis"


def main() -> None:
    records: List[Dict[str, Any]] = json.loads(_METRICS.read_text(encoding="utf-8"))["records"]

    bands: List[Dict[str, Any]] = []
    lines: List[str] = ["<!-- generated by clip_band_analysis.py; do not edit by hand -->", "",
                        "### What a CLIP score means, against what the eye sees", "",
                        "| what the image is | judged on | images | minimum | median | maximum |",
                        "|---|---|---|---|---|---|"]
    for label, description, sheet, selector in _GROUPS:
        values = sorted(r["clip_own_prompt"] for r in records if selector(r))
        if not values:
            continue
        bands.append({"label": label, "description": description, "judged_on": sheet,
                      "images": len(values), "minimum": min(values), "median": median(values),
                      "maximum": max(values), "mean": round(mean(values), 3)})
        lines.append(f"| {label} — {description} | {sheet} | {len(values)} | {min(values):.2f} "
                     f"| {median(values):.2f} | {max(values):.2f} |")

    # The noise floor: good 768 images of ONE entity at different seeds.
    same_entity = sorted(
        (r["seed"], r["clip_own_prompt"]) for r in records
        if r["entity"] == _NOISE_FLOOR_ENTITY
        and r["block"] in {"sign_off_768_off", "verify_refactored_base"})
    seen: Dict[int, float] = {}
    for seed, value in same_entity:
        seen.setdefault(seed, value)
    values = list(seen.values())
    floor = {
        "entity": _NOISE_FLOOR_ENTITY,
        "seeds": sorted(seen),
        "values": [seen[s] for s in sorted(seen)],
        "minimum": min(values), "maximum": max(values),
        "range": round(max(values) - min(values), 3),
        "standard_deviation": round(pstdev(values), 3),
    }
    lines += ["", "### The noise floor for clip_diff", "",
              f"One entity ({_NOISE_FLOOR_ENTITY.replace('_', ' ')}), 768 pixels, frozen "
              "hyperparameters, good photographs at every seed:", "",
              "| seed | CLIP |", "|---|---|"]
    for seed in sorted(seen):
        lines.append(f"| {seed} | {seen[seed]:.2f} |")
    lines += ["",
              f"- number of seeds: {len(values)}",
              f"- range: {floor['minimum']:.2f} to {floor['maximum']:.2f}, i.e. {floor['range']:.2f} CLIP points",
              f"- standard deviation: {floor['standard_deviation']:.2f}",
              ""]

    _TABLE.write_text("\n".join(lines), encoding="utf-8")
    _RESULT.write_text(json.dumps({"bands": bands, "clip_diff_noise_floor": floor}, indent=2),
                       encoding="utf-8")
    for band in bands:
        print(f"{band['label']:<28} n={band['images']:>2}  min {band['minimum']:.2f}  "
              f"median {band['median']:.2f}  max {band['maximum']:.2f}")
    print(f"noise floor over {len(values)} seeds of {_NOISE_FLOOR_ENTITY}: range "
          f"{floor['range']:.2f}, standard deviation {floor['standard_deviation']:.2f}")
    print(f"CLIP_BAND_ANALYSIS_DONE written={_TABLE}")


if __name__ == "__main__":
    main()
