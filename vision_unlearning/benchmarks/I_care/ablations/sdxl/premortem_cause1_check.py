'''
S5's sign-off gate against premortem cause 1 (plan section 8): before generating the remaining ten
checkpoints, check whether the target and its nine receivers show any interference at epochs 1/3/5, or
whether every receiver already sits inside the noise floor -- itself a reportable finding (plan D2's
stated risk), not a stage failure, but one that makes the D2 random-ten control load-bearing rather
than optional.

Reads `assets/campaign_seed{seed}.json` (already generated by run_campaign.py, no new images), scores
`clip_diff` for every (epoch, entity) pair at epochs 1/3/5 plus the target/each receiver's own off-
baseline, and writes `assets/premortem_cause1_seed{seed}.json`. CPU-safe, no SDXL pipeline loaded.

    python premortem_cause1_check.py --seed 42
'''
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Dict, List

_HERE = Path(__file__).resolve().parent
_OUT = _HERE / "assets"
_SELECTION = _HERE.parent / "every_epoch" / "assets" / "selection_people.json"
_EPOCHS = [1, 3, 5]


def main() -> None:
    from PIL import Image
    from vision_unlearning.metrics.image_and_text import MetricImageTextSimilarity

    parser = argparse.ArgumentParser(description="S5 premortem-cause-1 sign-off: clip_diff at epochs 1/3/5.")
    parser.add_argument("--seed", type=int, required=True, choices=[42, 43])
    args = parser.parse_args()

    manifest_path = _OUT / f"campaign_seed{args.seed}.json"
    rows = json.loads(manifest_path.read_text(encoding="utf-8"))
    by_epoch_entity: Dict[Any, Dict[str, str]] = {}
    for row in rows:
        by_epoch_entity.setdefault(row["epoch"], {})[row["entity"]] = row["path"]

    selection = json.loads(_SELECTION.read_text(encoding="utf-8"))
    target_name = selection["target"]["name"]
    receiver_names = [r["name"] for r in selection["receivers"]]
    entities = [target_name] + receiver_names

    from vision_unlearning.datasets.testbed import get_target_overwrite
    prompt_of = {n: f"An image of {get_target_overwrite('people', 'distil', n)[0]}" for n in entities}

    metric = MetricImageTextSimilarity(metrics=["clip"])
    off_paths = by_epoch_entity[None]
    clip_off: Dict[str, float] = {}
    for name in entities:
        img = Image.open(off_paths[name]).convert("RGB")
        clip_off[name] = metric.score_batch_same_text([img], prompt_of[name])[0]["clip"]

    trajectory: Dict[str, List[Dict[str, Any]]] = {name: [] for name in entities}
    for epoch in _EPOCHS:
        for name in entities:
            path = by_epoch_entity[epoch][name]
            img = Image.open(path).convert("RGB")
            clip_on = metric.score_batch_same_text([img], prompt_of[name])[0]["clip"]
            clip_diff = clip_on - clip_off[name]
            trajectory[name].append({"epoch": epoch, "clip_on": clip_on, "clip_off": clip_off[name], "clip_diff": clip_diff})

    # Noise floor reference (people, Stable Diffusion 1.4, median 2.81) -- printed for scale only, not
    # a pass/fail gate; the finding is reported regardless of the outcome (plan D2).
    every_epoch_floor = json.loads(
        (_HERE.parent / "every_epoch" / "assets" / "noise_floor_people.json").read_text(encoding="utf-8")
    )["summary"]["median"]

    receivers_within_floor_at_epoch5 = [
        name for name in receiver_names
        if abs(trajectory[name][-1]["clip_diff"]) <= every_epoch_floor
    ]

    result = {
        "seed": args.seed,
        "epochs": _EPOCHS,
        "target": target_name,
        "receivers": receiver_names,
        "trajectory": trajectory,
        "reference_noise_floor_median_sd1_4": every_epoch_floor,
        "receivers_within_floor_at_epoch5": receivers_within_floor_at_epoch5,
        "all_receivers_within_floor_at_epoch5": len(receivers_within_floor_at_epoch5) == len(receiver_names),
    }
    (_OUT / f"premortem_cause1_seed{args.seed}.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
